import { KIT_TR909 } from './tr909.mjs';
import { KIT_DUSTY_LOFI } from './dusty-lofi.mjs';
import { KIT_BRUSHED_JAZZ } from './brushed-jazz.mjs';
import { KIT_INDUSTRIAL } from './industrial.mjs';
import { KIT_CHIP8 } from './chip8.mjs';
import { KIT_ORCHESTRAL } from './orchestral.mjs';
// Sample-backed kits: GENERATED by tools/build-timbre-packs.mjs, each pinning its curated pack.
import { KIT_LINNDRUM } from './linndrum.mjs';
import { KIT_CR78 } from './cr78.mjs';
import { KIT_VINYL_INDIE } from './vinyl-indie.mjs';
import { KIT_FOUND_WOOD } from './found-wood.mjs';
import { KIT_DYSTOPIAN_TECH } from './dystopian-tech.mjs';
import { KIT_SYNARE_SDS } from './synare-sds.mjs';
import { KIT_TR707 } from './tr707.mjs';

import { TRIMS } from '../trims.mjs';

const ALL = [KIT_TR808, KIT_TR909, KIT_DUSTY_LOFI, KIT_BRUSHED_JAZZ, KIT_INDUSTRIAL, KIT_CHIP8, KIT_ORCHESTRAL, KIT_LINNDRUM, KIT_CR78, KIT_VINYL_INDIE, KIT_FOUND_WOOD, KIT_DYSTOPIAN_TECH, KIT_SYNARE_SDS, KIT_TR707];

function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) deepFreeze(child);
    Object.freeze(value);
  }
  return value;
}

/** Apply the generated loudness trims (linear, after shaping) to one lane. */
function trimLane(lane, key) {
  if (lane.variants) {
    return { ...lane, variants: Object.fromEntries(Object.entries(lane.variants).map(([name, v]) => [name, trimLane(v, `${key}:${name}`)])) };
  }
  const trim = TRIMS[key];
  if (trim === undefined) return lane;
  return lane.sample !== undefined
    ? { ...lane, gain: Number(((lane.gain ?? 1) * trim).toFixed(5)) }
    : { ...lane, level: Number(((lane.level ?? 1) * trim).toFixed(5)) };
}

function trimKit(kit) {
  return { ...kit, lanes: Object.fromEntries(Object.entries(kit.lanes).map(([name, lane]) => [name, trimLane(lane, `kit:${kit.id}:${name}`)])) };
}

export const KITS = deepFreeze(Object.fromEntries(ALL.map((kit) => [kit.id, trimKit(kit)])));
export const KIT_IDS = Object.freeze(Object.keys(KITS));
