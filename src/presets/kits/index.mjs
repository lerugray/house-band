/**
 * Registry of named drum kits (kit 1.11.0 Timbre Range). A kit is DATA: layered
 * synth lanes and/or sample lanes the engine in src/kit/band.js interprets. A
 * score selects one with `kit: "<id>"` (whole score), a track-level `kit`, or an
 * event's `opts.kit`.
 */
