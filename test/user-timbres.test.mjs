const root = fileURLToPath(new URL('..', import.meta.url));
const compose = join(root, 'src', 'compose.mjs');
const buildCli = join(root, 'tools', 'samples', 'build.mjs');
const SR = 44100;

/** Deterministic decaying noise burst (an unpitched drum hit), canonical PCM16 mono. */
function hitWav(seconds, seed) {
  const count = Math.round(seconds * SR);
  const frames = new Int16Array(count);
  let x = seed >>> 0;
  for (let i = 0; i < count; i++) {
    x = (Math.imul(x, 1664525) + 1013904223) >>> 0;
    frames[i] = Math.round(((x / 0xffffffff) * 2 - 1) * 20000 * Math.exp(-i / (count / 5)));
  }
  return Buffer.from(encodeCanonicalWav(frames));
}

/** One-second sine at a MIDI note (a pitched zone the builder can measure). */
function toneWav(midi) {
  const frames = new Int16Array(SR);
  const freq = midiToFrequency(midi);
  for (let i = 0; i < SR; i++) frames[i] = Math.round(Math.sin((2 * Math.PI * freq * i) / SR) * 16000);
  return Buffer.from(encodeCanonicalWav(frames));
}

/** A score on the current kit: user kit at score level, user patch at score level and on one event. */
function userScore(extra = {}) {
  return {
    schemaVersion: '1.1.0',
    kitVersion: { ...KIT_VERSION },
    seed: 13,
    tempo: 120,
    sampleRate: SR,
    gain: 0.5,
    kit: 'user:t',
    patches: { pluck: 'user:keys' },
    register: { name: 'kit-demo', briefRef: 'docs/REGISTER-KIT-DEMO.md' },
    tracks: {
      T: {
        bpm: 120,
        len: 16,
        vol: 0.8,
        steps: [
          { i: [0, 8], voice: 'kick', opts: { vol: 0.4 } },
          { i: 10, voice: 'kick', opts: { vol: 0.4, variant: 'b' } },
          { i: [4, 12], voice: 'snare', opts: { vol: 0.3 } },
          { every: 2, voice: 'hat', opts: { vol: 0.2 } },
          { i: 14, voice: 'tomLow', opts: { vol: 0.3 } },
          { i: 6, voice: 'clap', opts: { vol: 0.3 } },
          { i: 0, voice: 'pluck', note: 'C4', dur: 0.4, opts: { vol: 0.3 } },
          { i: 8, voice: 'pluck', note: 'G3', dur: 0.4, opts: { vol: 0.3, patch: 'user:keys' } },
        ],
      },
    },
    sections: [{ track: 'T', bars: 1, fadeIn: 0 }],
    ...extra,
  };
}

let tmp;
let packs;
let env;

function validated(score, environment = env, options = {}) {
  return validateSpec(structuredClone(score), { userTimbres: loadUserTimbres(score, environment, options) });
}

describe('user: kits and patches (OSS-13)', () => {
  before(() => {
    tmp = mkdtempSync(join(tmpdir(), 'hb-user-timbres-'));
    packs = join(tmp, 'packs');
    const src = join(tmp, 'src');
    mkdirSync(src, { recursive: true });
    const files = {
      'kick-a.wav': hitWav(0.25, 1),
      'kick-b.wav': hitWav(0.3, 2),
      'snare-a.wav': hitWav(0.2, 3),
      'hat-closed.wav': hitWav(0.08, 4),
      'tone-048-100.wav': toneWav(48),
      'tone-060-100.wav': toneWav(60),
      'tone-072-100.wav': toneWav(72),
    };
    for (const [name, bytes] of Object.entries(files)) writeFileSync(join(src, name), bytes);
    const config = {
      format: 'house-band-samples',
      version: 1,
      id: 't',
      displayName: 'User timbre test kit',
      source: { type: 'folder', path: './src' },
      licence: 'test fixture generated by code',
      fallbackKit: 'tr808',
      kit: { kick: { a: 'kick-a.wav', b: 'kick-b.wav' }, snare: { a: 'snare-a.wav' }, hat: { closed: 'hat-closed.wav' } },
      patches: { keys: { class: 'pluck', zones: 'auto', files: ['tone-048-100.wav', 'tone-060-100.wav', 'tone-072-100.wav'] } },
    };
    const configPath = join(tmp, 'house-band.samples.json');
    writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);
    const r = spawnSync(process.execPath, [buildCli, configPath, '--out', packs], { cwd: root, encoding: 'utf8' });
    assert.equal(r.status, 0, `samples build failed:\n${r.stdout}\n${r.stderr}`);
    env = { ...process.env, HOUSE_BAND_PACKS: packs };
  });

  after(() => {
    if (tmp) rmSync(tmp, { recursive: true, force: true });
  });

  it('a user pack with its kit and patch files still loads as a sample pack', async () => {
    const pack = await loadSamplePackDirectory(join(packs, 'user-t'));
    assert.equal(pack.manifest.packId, 'user-t');
  });

  it('resolves user:t from house-band.kit.json and user:keys from house-band.patches.json', () => {
    const registry = loadUserTimbres(userScore(), env);
    assert.deepEqual(Object.keys(registry.errors), []);
    const kitFile = JSON.parse(readFileSync(join(packs, 'user-t', 'house-band.kit.json'), 'utf8'));
    const patchesFile = JSON.parse(readFileSync(join(packs, 'user-t', 'house-band.patches.json'), 'utf8'));
    const kit = registry.kits['user:t'];
    assert.equal(kit.def.id, 'user:t');
    assert.equal(kit.def.kind, 'sample');
    assert.equal(kit.entrySha256, sha256(canonicalJson(kitFile)));
    assert.equal(registry.patches['user:keys'].entrySha256, sha256(canonicalJson(patchesFile.keys)));
    assert.equal(registry.patches['user:keys'].def.engine, 'sample');
    assert.deepEqual(registry.patches['user:keys'].def.params.zones.map((z) => [z.lo, z.hi, z.root]), [[0, 54, 48], [55, 66, 60], [67, 127, 72]]);
    assert.equal(userPackFormatVersion(registry), JSON.parse(readFileSync(join(packs, 'user-t', 'pack.json'), 'utf8')).formatVersion);
  });

  it('a score naming user:t and a user: patch renders twice to identical bytes, with user custody in the manifest', async () => {
    const a = await renderSpecToWav(validated(userScore()));
    const b = await renderSpecToWav(validated(userScore()));
    assert.ok(a.wav.length > 44);
    assert.equal(sha256(a.wav), sha256(b.wav));
    assert.equal(a.manifest.output.sha256, b.manifest.output.sha256);

    const pack = JSON.parse(readFileSync(join(packs, 'user-t', 'pack.json'), 'utf8'));
    const kitFile = JSON.parse(readFileSync(join(packs, 'user-t', 'house-band.kit.json'), 'utf8'));
    const patchesFile = JSON.parse(readFileSync(join(packs, 'user-t', 'house-band.patches.json'), 'utf8'));
    const [kitRow] = a.manifest.timbre.kits;
    assert.equal(kitRow.id, 'user:t');
    assert.deepEqual(kitRow.user, {
      packId: 'user-t',
      manifestSha256: pack.manifestSha256,
      contentSha256: pack.contentSha256,
      file: 'house-band.kit.json',
      entrySha256: sha256(canonicalJson(kitFile)),
      fallbackKit: { id: 'tr808', sha256: sha256(canonicalJson(KITS.tr808)), lanes: ['tomLow', 'tomMid', 'tomHigh', 'clap', 'rim', 'ride', 'crash', 'perc'] },
    });
    const [patchRow] = a.manifest.timbre.patches;
    assert.equal(patchRow.id, 'user:keys');
    assert.deepEqual(patchRow.user, {
      packId: 'user-t',
      manifestSha256: pack.manifestSha256,
      contentSha256: pack.contentSha256,
      file: 'house-band.patches.json',
      entrySha256: sha256(canonicalJson(patchesFile.keys)),
    });
    assert.equal(a.manifest.timbre.defaultKit, 'user:t');
    assert.ok(!JSON.stringify(a.manifest).includes(tmp), 'the manifest names no local path');
  });

  it('the user samples are what plays: the same score on tr808 renders different bytes', async () => {
    const drumsOnly = (kit) => {
      const s = userScore({ kit });
      delete s.patches;
      s.tracks.T.steps = s.tracks.T.steps.filter((e) => e.voice !== 'pluck');
      return s;
    };
    const user = await renderSpecToWav(validated(drumsOnly('user:t')));
    const synth = await renderSpecToWav(validateSpec(drumsOnly('tr808')));
    assert.notEqual(sha256(user.wav), sha256(synth.wav));
    // The user patch sounds, and is not the historical pluck voice.
    const plucks = (patches) => {
      const s = userScore({ patches });
      delete s.kit;
      s.tracks.T.steps = s.tracks.T.steps.filter((e) => e.voice === 'pluck').map((e) => ({ ...e, opts: { vol: 0.3 } }));
      if (!patches) delete s.patches;
      return s;
    };
    const userPluck = await renderSpecToWav(validated(plucks({ pluck: 'user:keys' })));
    const plainPluck = await renderSpecToWav(validateSpec(plucks(undefined)));
    assert.ok(Buffer.from(userPluck.wav).subarray(44).some((byte) => byte !== 0));
    assert.notEqual(sha256(userPluck.wav), sha256(plainPluck.wav));
  });

  it('lanes missing from the user kit play the fallback kit lane and are reported', async () => {
    const artifact = validated(userScore());
    assert.equal(kitDefFor(artifact, 'user:t').lanes.tomLow, KITS.tr808.lanes.tomLow);
    assert.equal(kitDefFor(artifact, 'user:t').lanes.clap, KITS.tr808.lanes.clap);
    assert.notEqual(kitDefFor(artifact, 'user:t').lanes.kick, KITS.tr808.lanes.kick);
    assert.equal(patchDefFor(artifact, 'user:keys').class, 'pluck');
    assert.deepEqual(userKitFallbackNotes(artifact), ['user kit t: tomLow, clap play tr808']);
    // The fallback lane sounds: a score of only the missing lane is not silent.
    const only = userScore({ patches: undefined });
    delete only.patches;
    only.tracks.T.steps = [{ i: 0, voice: 'tomLow', opts: { vol: 0.5 } }];
    const r = await renderSpecToWav(validated(only));
    assert.ok(Buffer.from(r.wav).subarray(44).some((byte) => byte !== 0));
  });

  it('variants are checked against the user kit', () => {
    const bad = userScore();
    bad.tracks.T.steps[1].opts.variant = 'c';
    assert.throws(() => validated(bad), (e) => e instanceof SpecError && /variant: "c" is not one of a, b/.test(e.message));
  });

  it('compose --kit-map tr707=user:t renders and prints the fallback lanes', () => {
    const score = userScore({ kit: 'tr707' });
    delete score.patches;
    score.tracks.T.steps = score.tracks.T.steps.filter((e) => e.voice !== 'pluck');
    const dir = join(tmp, 'kit-map');
    mkdirSync(dir, { recursive: true });
    const specPath = join(dir, 'score.json');
    writeFileSync(specPath, JSON.stringify(score));
    const out = join(dir, 'x.wav');
    const r = spawnSync(process.execPath, [compose, '--spec', specPath, '--kit-map', 'tr707=user:t', '--out', out], {
      cwd: root, encoding: 'utf8', env: { ...env, HOUSE_BAND_PALETTE_CHECK: 'off' },
    });
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stderr, /kit-map: tr707 -> user:t \(1 references\)/);
    assert.match(r.stderr, /user kit t: tomLow, clap play tr808/);
    assert.ok(existsSync(out));
    const manifest = JSON.parse(readFileSync(`${out}.manifest.json`, 'utf8'));
    assert.equal(manifest.kitMap.replaced, 1);
    assert.equal(manifest.timbre.kits[0].id, 'user:t');
    assert.equal(manifest.timbre.kits[0].user.packId, 'user-t');
  });

  it('a missing user kit fails validation naming the files searched and samples build', () => {
    const score = userScore({ kit: 'user:nope' });
    delete score.patches;
    score.tracks.T.steps = score.tracks.T.steps.filter((e) => e.voice !== 'pluck');
    assert.throws(() => validated(score), (e) => {
      assert.ok(e instanceof SpecError);
      assert.match(e.message, /^spec\.kit: user kit "user:nope" was not found\. Searched: /);
      assert.ok(e.message.includes(join(packs, 'user-nope', 'house-band.kit.json')), e.message);
      assert.ok(e.message.includes(join(root, 'sample-packs', 'user-nope', 'house-band.kit.json')), e.message);
      assert.match(e.message, /samples build/);
      return true;
    });
    // The compose CLI reports the same and exits 1.
    const specPath = join(tmp, 'nope.json');
    writeFileSync(specPath, JSON.stringify(score));
    const r = spawnSync(process.execPath, [compose, '--spec', specPath, '--out', join(tmp, 'nope.wav')], { cwd: root, encoding: 'utf8', env });
    assert.equal(r.status, 1);
    assert.match(r.stderr, /user kit "user:nope" was not found\. Searched: .*house-band\.kit\.json/);
  });

  it('a missing user patch fails validation naming the files searched; no registry at all says how to load one', () => {
    const score = userScore({ patches: { pluck: 'user:gone' } });
    score.tracks.T.steps = score.tracks.T.steps.filter((e) => e.voice !== 'pluck');
    assert.throws(() => validated(score), (e) => e instanceof SpecError
      && e.message.startsWith('spec.patches.pluck: user patch "user:gone" was not found. Searched: ')
      && e.message.includes(join(packs, 'user-*', 'house-band.patches.json'))
      && e.message.includes(join(packs, 'user-t', 'house-band.patches.json'))
      && /samples build/.test(e.message));
    assert.throws(() => validateSpec(userScore()), (e) => e instanceof SpecError && /user kit "user:t" is not loaded: load the user timbres/.test(e.message));
  });

  it('a user patch of the wrong class and a malformed kit file are validation errors', () => {
    const wrong = userScore({ patches: { bass: 'user:keys' } });
    wrong.tracks.T.steps = wrong.tracks.T.steps.filter((e) => e.voice !== 'pluck');
    assert.throws(() => validated(wrong), (e) => e instanceof SpecError && /patch "user:keys" is a pluck patch, not bass/.test(e.message));

    const broken = join(tmp, 'broken');
    cpSync(join(packs, 'user-t'), join(broken, 'user-t'), { recursive: true });
    const kitPath = join(broken, 'user-t', 'house-band.kit.json');
    const kitFile = JSON.parse(readFileSync(kitPath, 'utf8'));
    kitFile.lanes.kick.variants.a.sample = 'user-t/not-there';
    writeFileSync(kitPath, JSON.stringify(kitFile));
    const score = userScore();
    delete score.patches;
    score.tracks.T.steps = score.tracks.T.steps.filter((e) => e.voice !== 'pluck');
    assert.throws(() => validated(score, env, { roots: [broken] }), (e) => e instanceof SpecError
      && e.message.includes(`${kitPath} is not a usable user kit`)
      && e.message.includes('"user-t/not-there" is not in pack.json')
      && /samples build/.test(e.message));
  });

  it('the first user patch in search order wins and a later duplicate is reported once', () => {
    const second = join(tmp, 'second');
    cpSync(join(packs, 'user-t'), join(second, 'user-t'), { recursive: true });
    const logged = [];
    const log = (message) => logged.push(message);
    const roots = [packs, second];
    const registry = loadUserTimbres(userScore(), env, { roots, log });
    loadUserTimbres(userScore(), env, { roots, log });
    assert.equal(registry.patches['user:keys'].packDir, join(packs, 'user-t'));
    assert.equal(logged.length, 1);
    assert.equal(logged[0], `user patch "user:keys" is defined in more than one pack: using ${join(packs, 'user-t', 'house-band.patches.json')}, ignoring ${join(second, 'user-t', 'house-band.patches.json')}`);
  });

  it('a score with no user: name loads no registry, and the kit identity sha is unchanged', () => {
    const plain = userScore({ kit: 'tr808' });
    delete plain.patches;
    plain.tracks.T.steps = plain.tracks.T.steps.filter((e) => e.voice !== 'pluck');
    assert.equal(loadUserTimbres(plain, env), null);
    assert.equal(kitIdentitySha(root), KIT_VERSION.sha);
  });
});
