/** OSS-13: `user:` kits and patches in validation, timbre resolution, rendering and custody. */
import { after, before, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { midiToFrequency } from '../src/kit/band.js';
import { KITS } from '../src/presets/kits/index.mjs';
import { canonicalJson, sha256 } from '../src/provenance.mjs';
import { renderSpecToWav } from '../src/render.mjs';
