#!/usr/bin/env node
/**
 * Solve the bright-voice body-match trims (src/presets/bright-trims.mjs): for every bright voice (neutral bell and every
 * bright patch) render its Timbre Range proof phrase untreated and treated-without-trim (preset gainDb 0), at the
 * phrase's own register AND transposed down 1 and 2 octaves, and set the trim so that in the
 * WORST register the treated voice's 200 Hz-4 kHz power (L + R, whole render: dry + reverb + dark tail) equals the
 * untreated one: the static form of Darkness r10's band-matched rider. The dark tail builds up most under low-mid
 * notes (on Darkness 05-off-season a proof-register trim still left the bell +4.8 dB in body), so the trim takes the
 * worst case and the voice never comes out louder in body than untreated. Clamped to [-12, +6] dB.
 *   node tools/bright-voice/calibrate.mjs [--check]
 * --check: report how far each voice's body lands from (untreated + preset gainDb) with the CURRENT trims; writes nothing.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { renderSpecToWav } from '../../src/render.mjs';
import { validateSpec } from '../../src/spec.mjs';
import { brightPlan } from '../../src/timbre.mjs';
import { BRIGHT_VOICE_PRESETS, brightTrimKey } from '../../src/presets/bright.mjs';
import { PATCH_IDS_BY_CLASS } from '../../src/presets/patches/index.mjs';
import { phraseScore } from '../lib/timbre-proof-scores.mjs';
import { band, readStereo } from './measure.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const check = process.argv.includes('--check');
const preset = BRIGHT_VOICE_PRESETS.r10;
const bodyPower = (wav) => { const s = readStereo(wav); let p = 0; for (const x of [s.L, s.R]) { const y = band(x, s.sr, 200, 4000); for (let i = 0; i < y.length; i++) p += y[i] * y[i]; } return p; };

const REGISTERS = { bell: [0, -1, -2], lead: [0, -1, -2], pluck: [0, -1, -2] };
const shiftOctave = (note, by) => note.replace(/(-?\d+)$/, (d) => String(Math.max(1, Number(d) + by)));
function transposed(score, by) {
  if (by === 0) return score;
  const s = structuredClone(score);
  for (const t of Object.values(s.tracks)) for (const e of t.steps) if (typeof e.note === 'string') e.note = shiftOctave(e.note, by);
  return s;
}
const jobs = [];
for (const [cls, rule] of Object.entries(preset.classes)) {
  const ids = rule.patches === true ? [undefined, ...PATCH_IDS_BY_CLASS[cls]] : rule.patches;
  for (const patch of ids) jobs.push({ cls, patch });
}
const trims = {};
const rows = [];
for (const { cls, patch } of jobs) {
  let db = Infinity;
  const perRegister = [];
  for (const by of REGISTERS[cls]) {
    const score = transposed(phraseScore({ cls, patch }), by);
    const off = await renderSpecToWav(validateSpec({ ...score, brightVoice: 'off' }), {});
    const onScore = validateSpec({ ...score, brightVoice: 'r10' });
    const plan = brightPlan(onScore);
    const opts = check ? {} : { bright: { ...plan, preset: { ...plan.preset, gainDb: 0, trims: {} } } };
    const on = await renderSpecToWav(onScore, opts);
    const d = 10 * Math.log10(bodyPower(off.wav) / bodyPower(on.wav));
    perRegister.push(`${by}oct ${(-d).toFixed(2)}`);
    db = Math.min(db, d);
  }
  console.log(`  ${brightTrimKey(cls, patch)} body change by register: ${perRegister.join(', ')} dB`);
  const key = brightTrimKey(cls, patch);
  if (check) { const landed = -db; rows.push({ key, bodyVsUntreatedDb: +landed.toFixed(2), target: preset.gainDb }); console.log(`${key.padEnd(26)} body ${landed >= 0 ? '+' : ''}${landed.toFixed(2)} dB vs untreated (target ${preset.gainDb})`); continue; }
  trims[key] = Number(Math.max(-12, Math.min(6, db)).toFixed(2));
  console.log(`${key.padEnd(26)} untrimmed body ${(-db).toFixed(2)} dB -> trim ${trims[key]} dB`);
}
if (!check) {
  const body = Object.keys(trims).sort().map((k) => `  ${JSON.stringify(k)}: ${trims[k]},`).join('\n');
  writeFileSync(join(root, 'src', 'presets', 'bright-trims.mjs'), `/**
 * GENERATED by tools/bright-voice/calibrate.mjs. Do not edit by hand.
 * Body-match trims (dB) for the bright-voice treatment, keyed "class" (neutral voice) or "class:patch": the static
 * kit equivalent of Darkness r10's band-matched rider (loudnessDb 0, matchBand 200-4000 Hz). Solved on the Timbre
 * Range proof phrase of each bright voice (at its own register and 1-2 octaves down, worst case) so the treated voice
 * (dry + its reverb + the dark tail, before the preset's gainDb) never has more 200 Hz-4 kHz power than the untreated
 * voice. Clamped to [-12, +6] dB like the r10 rider.
 */
export const BRIGHT_TRIMS = Object.freeze({
${body}
});
`);
  console.log('wrote src/presets/bright-trims.mjs');
}
