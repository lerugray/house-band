#!/usr/bin/env node
/**
 * Write docs/TIMBRE-CATALOG.md from the kit and patch registries, so the list a
 * composer reads can never drift from the data the renderer uses.
 *
 *   node tools/timbre-catalog.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DRUM_LANES, PATCH_CLASSES } from '../src/kit/band.js';
import { KITS } from '../src/presets/kits/index.mjs';
import { PATCH_IDS_BY_CLASS, PATCHES } from '../src/presets/patches/index.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = [
  '# Timbre catalog (kit 1.11.0)', '',
  'GENERATED by `tools/timbre-catalog.mjs` from `src/presets/`; do not edit by hand.',
  'Pick a kit with `"kit": "<id>"` (whole score), a track-level `kit`, or an event `opts.kit`. Pick patches with',
  '`"patches": { "pad": "<id>" }` (whole score), a track-level `patches`, or an event `opts.patch`.',
  'Every score declares a `palette` and says how it differs from its siblings: see the Timbre-Variety Law in README.md.', '',
  '## Drum kits', '',
  '| id | kind | what it sounds like | lanes with variants |', '|---|---|---|---|',
];
for (const kit of Object.values(KITS)) {
  const variants = Object.entries(kit.lanes).filter(([, l]) => l.variants).map(([lane, l]) => `${lane}: ${Object.keys(l.variants).join('/')}`).join('; ');
  const missing = DRUM_LANES.filter((lane) => !kit.lanes[lane]);
  const gap = missing.length ? ` (no ${missing.join(', ')}: those use the neutral recipes)` : '';
  out.push(`| \`${kit.id}\` | ${kit.kind} | **${kit.title}.** ${kit.character}${gap} | ${variants || '-'} |`);
}
out.push('', 'Lanes: `kick snare hat tomLow tomMid tomHigh clap rim ride crash perc`. Every lane takes `vol`, `dur`, `tune` (semitones), `verb` and the fx sends, `kit`, `variant`, `nudge`.', '');
for (const cls of PATCH_CLASSES) {
  out.push(`## ${cls} patches`, '', '| id | engine | what it sounds like |', '|---|---|---|');
  for (const id of PATCH_IDS_BY_CLASS[cls]) out.push(`| \`${id}\` | ${PATCHES[id].engine}${PATCHES[id].pack ? ' (Ray\'s samples)' : ''} | **${PATCHES[id].title}.** ${PATCHES[id].character} |`);
  out.push('');
}
writeFileSync(join(root, 'docs', 'TIMBRE-CATALOG.md'), `${out.join('\n')}\n`);
console.log(`wrote docs/TIMBRE-CATALOG.md (${Object.keys(KITS).length} kits, ${Object.keys(PATCHES).length} patches)`);
